  movie_desc character varying not null,
  year bigint not null,
  age_rating character varying not null,
  duration bigint not null,
  genre text[] not null,
  created_at timestamp with time zone not null default now(),
  added_by bigint not null,
  image_url text null,
  constraint movie_pkey primary key (movie_id),
  constraint movie_movie_id_key unique (movie_id),
  constraint movie_added_by_fkey foreign KEY (added_by) references staff (staff_id) on update CASCADE on delete RESTRICT
) TABLESPACE pg_default;

