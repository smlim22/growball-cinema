create table public.staff (
  staff_id bigint generated by default as identity not null,
  staff_name character varying not null,
  "staff_phoneNo" character varying not null,
  access_level bigint not null default '1'::bigint,
  joined_at timestamp with time zone not null default now(),
  staff_email character varying not null,
  uuid uuid not null,
  status character varying not null,
  constraint staff_pkey primary key (staff_id),
  constraint staff_staff_id_key unique (staff_id),
  constraint staff_uuid_fkey foreign KEY (uuid) references auth.users (id) on update CASCADE on delete RESTRICT
) TABLESPACE pg_default;

create table public.movie (
